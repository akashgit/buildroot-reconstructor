def _domain_expertise_section() -> str:
    return """\
# Domain Expertise

## JAR Structure
- A JAR is a ZIP archive containing compiled .class files, resources, and META-INF/
- META-INF/MANIFEST.MF contains build metadata: Build-Jdk-Spec, Created-By, Bundle headers
- Multi-release JARs have META-INF/versions/9/, META-INF/versions/11/ etc.
- OSGI bundles have Bundle-SymbolicName, Export-Package, Import-Package in manifest

## Build Systems
- **Maven**: pom.xml, `mvn clean install -B -DskipTests -Dgpg.skip=true`
  - Maven wrapper: ./mvnw (needs chmod +x)
  - Multi-module: `-pl <module> -am` to build specific module
  - Reproducibility: `-Dproject.build.outputTimestamp=2000-01-01T00:00:00Z`
  - Shade plugin: repackages dependencies — match exact configuration
  - Assembly plugin: creates uber-JARs — check descriptor files
- **Gradle**: build.gradle/build.gradle.kts, `./gradlew build -x test`
  - Shadow plugin: like Maven shade — `tasks.shadowJar { mergeServiceFiles() }`
  - Publications: check which task produces the artifact
- **Ant**: build.xml, `ant jar` or `ant dist`
  - Exact version matters — pin to the version used originally
  - build.xml often has custom targets — read it carefully

## Bytecode & JDK Matching
- Different JDK versions produce different bytecode (major version number)
- JDK 8=52, 11=55, 17=61, 21=65
- Minor version matters: JDK 17.0.9 produces slightly different output than 17.0.10
- Match Build-Jdk-Spec from MANIFEST.MF to Docker image tag
- For multi-release JARs, compile versioned classes with the actual target JDK

## OSGI Bundles
- Bundle headers generated by tools like Bnd, maven-bundle-plugin, bnd-maven-plugin
- Bnd version matters — different versions format headers differently
- Export-Package and Import-Package must match exactly
- Bundle-Version often matches Maven version but may differ

## Code Signing
- Signed JARs have META-INF/*.SF, *.DSA, *.RSA files
- Cannot reproduce signatures without private keys
- The L4 comparator ignores signature files — don't worry about them
- Add -Dgpg.skip=true to Maven builds to skip GPG signing

## Reproducibility
- Always set SOURCE_DATE_EPOCH=0 for timestamp consistency
- Maven: -Dproject.build.outputTimestamp=2000-01-01T00:00:00Z
- JVM: -XX:-UsePerfData to suppress hsperfdata files

## JAR Staging
After building, always stage the target JAR to a known path so the evaluator finds \
the right artifact (especially in multi-module projects or builds with shaded/dependency JARs):
```dockerfile
RUN mkdir -p /output && cp target/artifact-1.0.jar /output/rebuilt.jar
```
The evaluator checks `/output/rebuilt.jar` first. Without this, it guesses from all JARs \
in target/ using substring matching, which can pick the wrong file.

## v3 Template Limitations
The v3 pipeline uses Jinja2 templates for single-stage builds. It CANNOT express:
- Multi-stage Docker builds (multiple FROM statements)
- Cross-stage artifact copying (COPY --from=stage1)
- Multiple JDK installations in one build
- Complex Bnd/OSGI wrapping pipelines
- Custom file manipulations beyond pre/post build commands
- Conditional logic based on build output

When you see these needs, take over and write the Containerfile directly."""


def _eval_infrastructure_section() -> str:
    return """\
# Evaluation Infrastructure

## L1-L4 Scoring
- **L1 Parse (0.05)**: Containerfile parses as valid Dockerfile syntax
- **L2 Build (0.10)**: Container image builds successfully via Podman
- **L3 Command (0.35)**: Built image contains a JAR file in expected paths
- **L4 Match (0.50)**: Rebuilt JAR matches original from Maven Central

## L4 Comparison
The JAR comparator checks three dimensions:
- **Structural**: Same file entries (classes, resources) — missing/extra files
- **Metadata**: MANIFEST.MF headers match — Build-Jdk, OSGI headers, custom attributes
- **Bytecode**: Class files produce identical bytecode — checked via SHA comparison

## Scoring Formula
```
reward = 0.05 * L1 + 0.10 * L2 + 0.35 * L3 + 0.50 * L4_score
```
L4_score is the equivalence_score() from the comparison report (0.0 to 1.0).
A reward >= 0.98 means near-perfect reproduction.

## Comparison Report
When L3 passes, read the comparison report carefully:
- `verdict`: IDENTICAL, EQUIVALENT, DIVERGENT, or FAILED
- `structural.match` + `structural.diff.missing` / `structural.diff.extra`
- `metadata.match` + `metadata.manifest_diff_keys`
- `bytecode.match` + `bytecode.classes_divergent`

Focus your fixes on whichever dimension is failing.

## L4' Approximate Scoring (when reference JAR unavailable)

When the original JAR is not on Maven Central, L4 uses approximate scoring (L4')
with 2 signals:
- **Bytecode version match (0.60)**: Built .class major version matches expected JDK
- **Manifest sanity (0.40)**: MANIFEST.MF has Manifest-Version + pom.properties has correct GAV

L4' score replaces L4 in the reward formula. Check `l4_signal_source` in eval output:
- `"full_comparison"` = normal L4 (reference JAR comparison)
- `"fallback_signals"` = L4' (approximate, 2-signal)

To improve L4' score: ensure the correct JDK version is used (bytecode match) and
that the build produces correct GAV metadata in pom.properties (manifest sanity).

### Recovering full L4 when the reference JAR is not found
The evaluator automatically searches Maven Central for the canonical coordinate when the fork
coordinate 404s (handles cases like `tools.jackson.core` → `com.fasterxml.jackson.core`).

If eval still reports "JAR unavailable", the artifact name may have changed too. You should try
to find the canonical reference JAR yourself:

1. **Search Maven Central** — `curl 'https://search.maven.org/solrsearch/select?q=a:"ARTIFACT"&wt=json'`
   to find all groupIds that publish an artifact with a similar name.
2. **Common renames to check**: `commons-dbcp` → `commons-dbcp2`, `hikaricp` → `HikariCP`,
   `bouncy-castle` → `bcprov-jdk18on`, `json-java` → `json`, `antlr` → `antlr4-runtime`.
   Many forks just republish upstream JARs under a different groupId and sometimes a different artifactId.
3. **WSO2 orbit bundles** (`org.wso2.orbit.*`) repackage upstream JARs — strip the `org.wso2.orbit.`
   prefix to find the upstream groupId (e.g. `org.wso2.orbit.org.yaml:snakeyaml` → `org.yaml:snakeyaml`).
4. **Web search** for the artifact name + "maven central" to find the canonical coordinate.
5. Once found, download the canonical JAR and compare directly:
   ```bash
   # Download canonical reference JAR (Google mirror preferred, Maven Central as fallback)
   curl -f -o /tmp/reference.jar 'https://maven-central.storage-download.googleapis.com/maven2/com/zaxxer/HikariCP/2.7.3/HikariCP-2.7.3.jar' \
     || curl -f -o /tmp/reference.jar 'https://repo1.maven.org/maven2/com/zaxxer/HikariCP/2.7.3/HikariCP-2.7.3.jar'
   # Compare with your rebuilt JAR using the jar comparator
   python -c "from buildroot.utils.jar_comparator import compare_jars; r = compare_jars('/tmp/reference.jar', '/path/to/rebuilt.jar', 'coord'); print(r.verdict, r.equivalence_score())"
   ```"""


